#!/usr/bin/env python3
"""Regenerate the Android Baseline Profile from cold starts of the installed release build.

Install a release build first (`npm run perf:android:device`). The script clears the app's
compiled code and profiles, cold-starts it, dumps the classes and methods ART recorded, and
writes them as `android/app/src/main/baseline-prof.txt`. AGP merges that file into the APK's
`assets/dexopt/baseline.prof`, so the first launch after an install or update starts with startup
code already compiled instead of interpreted.

Needs Android 13+ (`pm dump-profiles` works on release builds there). Release builds are not
minified; if R8 obfuscation is enabled later, regenerate from an unminified build so the rules use
source names. App data and settings are kept.
"""

import argparse
import re
import subprocess
import time
from pathlib import Path


PACKAGE = "com.anonymous.quranappmobile"
ACTIVITY = f"{PACKAGE}/.MainActivity"
DEFAULT_OUTPUT = Path(__file__).resolve().parents[2] / "android/app/src/main/baseline-prof.txt"
# Class rules (`Lcom/Foo;`) and method rules with ART hotness flags (`HSPLcom/Foo;->bar()V`).
RULE = re.compile(r"^(?:[HSP]+)?L[^;\s]+;(?:->\S+)?$")
HEADER = """# Generated by scripts/perf/android-baseline-profile.py from cold starts to Home.
# Regenerate after large startup changes; do not edit by hand.
"""


def adb(*args):
    return subprocess.run(["adb", *args], check=True, capture_output=True, text=True).stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--runs", type=int, default=4, help="cold starts to record")
    parser.add_argument("--settle", type=float, default=8.0, help="seconds to stay on Home per run")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    if args.runs < 1:
        parser.error("--runs must be positive")

    sdk = int(adb("shell", "getprop", "ro.build.version.sdk").strip())
    if sdk < 33:
        raise SystemExit(f"Android 13+ is required to dump release profiles (device API {sdk}).")

    # Start from interpreted code with no saved profile, so the dump holds only what startup runs.
    adb("shell", "am", "force-stop", PACKAGE)
    adb("shell", "cmd", "package", "compile", "--reset", PACKAGE)

    for index in range(args.runs):
        adb("shell", "am", "force-stop", PACKAGE)
        time.sleep(1)
        adb("shell", "am", "start", "-W", "-n", ACTIVITY)
        time.sleep(args.settle)
        print(f"cold start {index + 1}/{args.runs} recorded", flush=True)

    dump = adb("shell", "pm", "dump-profiles", "--dump-classes-and-methods", PACKAGE)
    remote = re.search(r"Profile saved to '([^']+)'", dump)
    if not remote:
        raise SystemExit(f"ART did not dump a profile:\n{dump}")
    profile = adb("shell", "cat", remote.group(1))
    adb("shell", "am", "force-stop", PACKAGE)

    rules = sorted({line.strip() for line in profile.splitlines() if RULE.match(line.strip())})
    if not rules:
        raise SystemExit("The dumped profile contained no class or method rules.")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(HEADER + "\n".join(rules) + "\n")
    print(f"wrote {len(rules)} rules to {args.output}")


if __name__ == "__main__":
    main()
